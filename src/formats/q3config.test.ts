import { describe, expect, it } from 'vitest';

import { K, stringToKey } from './q3-keys';
import { commandLines, configCommands, tokenize, writeConfig, type ArchivedCvar } from './q3config';

describe('commandLines', () => {
  it('ends a line at a newline, or at a semicolon outside quotes', () => {
    expect(commandLines('bind a "x;y"; bind b z\nseta c 1')).toEqual([
      'bind a "x;y"',
      ' bind b z',
      'seta c 1'
    ]);
    expect(commandLines('a\n')).toEqual(['a']);
  });

  it('counts a carriage return as a line break of its own', () => {
    expect(commandLines('a\r\nb')).toEqual(['a', '', 'b']);
  });

  it('keeps the semicolons in a // comment on its line', () => {
    expect(commandLines('// a; b\nbind c d')).toEqual(['// a; b', 'bind c d']);
  });

  it("keeps a block comment's newlines and semicolons to itself", () => {
    expect(commandLines('bind a b /* c;\nd */ bind e f')).toEqual(['bind a b /* c;\nd *', ' bind e f']);
  });
});

describe('tokenize', () => {
  it("splits on any whitespace, as pak0's default.cfg lines up its binds with tabs", () => {
    expect(tokenize('bind\t[           weapprev')).toEqual(['bind', '[', 'weapprev']);
    expect(tokenize('bind \\ +mlook')).toEqual(['bind', '\\', '+mlook']);
  });

  it('keeps a quoted token whole, with no escapes', () => {
    expect(tokenize('seta cg_crosshairrgb "1 1 1 1"')).toEqual(['seta', 'cg_crosshairrgb', '1 1 1 1']);
    expect(tokenize('seta name ""')).toEqual(['seta', 'name', '']);
    expect(tokenize('bind x "open')).toEqual(['bind', 'x', 'open']);
  });

  it('ends a bare token at a quote or a comment', () => {
    expect(tokenize('seta a"b"')).toEqual(['seta', 'a', 'b']);
    expect(tokenize('bind a/* x */b')).toEqual(['bind', 'a', 'b']);
    expect(tokenize('bind a b // c d')).toEqual(['bind', 'a', 'b']);
  });

  it('finds nothing in a blank line or a comment', () => {
    expect(tokenize('   ')).toEqual([]);
    expect(tokenize('// KEY BINDINGS')).toEqual([]);
  });

  it('takes a quote as a character like any other when told to ignore quotes', () => {
    expect(tokenize('echo "a b"c', true)).toEqual(['echo', '"a', 'b"c']);
    expect(tokenize('"" x', true)).toEqual(['""', 'x']);
    expect(tokenize('a"b // c', true)).toEqual(['a"b']);
    expect(tokenize('echo "a b"c')).toEqual(['echo', 'a b', 'c']);
  });
});

describe('configCommands', () => {
  it('reads every line with its quotes, whatever its place among the lines', () => {
    expect(configCommands('bind a "x y"\nbind b "x y"')).toEqual([
      ['bind', 'a', 'x y'],
      ['bind', 'b', 'x y']
    ]);
  });
});

describe('writeConfig', () => {
  it("writes Q3's layout: the header, unbindall, the binds in key order, then the cvars", () => {
    const text = writeConfig(
      [
        [K.MWHEELUP, 'weapprev'],
        [119, '+forward'],
        [K.SPACE, '+moveup'],
        [59, 'say ok'],
        [K.MOUSE1, '']
      ],
      [
        { name: 'cg_fov', value: '89.2' },
        { name: 'name', value: 'UnnamedPlayer' }
      ]
    );
    expect(text).toBe(
      [
        '// generated by playcanvas-quake3, do not modify',
        'unbindall',
        'bind SPACE "+moveup"',
        'bind SEMICOLON "say ok"',
        'bind w "+forward"',
        'bind MWHEELUP "weapprev"',
        'seta cg_fov "89.2"',
        'seta name "UnnamedPlayer"',
        ''
      ].join('\n')
    );
  });

  it("writes no unbindall and no binds with no bind table, as ioq3ded's file has none", () => {
    expect(writeConfig(undefined, [{ name: 'sv_hostname', value: 'Rats' }])).toBe(
      '// generated by playcanvas-quake3, do not modify\nseta sv_hostname "Rats"\n'
    );
  });

  it('reads back to the same binds and cvars', () => {
    const binds: [number, string][] = [
      [92, '+mlook'],
      [34, 'weapon 1'],
      [K.SHIFT, '+movedown'],
      [K.MWHEELDOWN, 'weapnext'],
      [K.PAD0_A, '+attack']
    ];
    const cvars: ArchivedCvar[] = [
      { name: 'cg_crosshairrgb', value: '1 1 1 1' },
      { name: 'name', value: '^1Unnamed^7Player' },
      { name: 'r_overBrightBits', value: '' }
    ];

    const read = new Map<number, string>();
    const readCvars: ArchivedCvar[] = [];
    for (const argv of configCommands(writeConfig(binds, cvars))) {
      if (argv[0] === 'unbindall') read.clear();
      else if (argv[0] === 'bind') read.set(stringToKey(argv[1]), argv.slice(2).join(' '));
      else if (argv[0] === 'seta') readCvars.push({ name: argv[1], value: argv.slice(2).join(' ') });
    }

    expect(read).toEqual(new Map(binds));
    expect(readCvars).toEqual(cvars);
  });
});
