import { keyToString } from './q3-keys';

export { commandLines, configCommands, tokenize } from '../../scripts/q3-commands.mjs';

/**
 * `q3config.cfg`, read and written as Quake 3 does.
 *
 * Reading splits the text into commands as `exec` does, with Q3's quoting and comments
 * (`scripts/q3-commands.mjs`, which the desktop shell reads it by too); running them is the
 * settings' business (`settings/game-config.ts`). Writing gives Q3's own layout: the header,
 * `unbindall`, a `bind` for every bound key in key order, then a `seta` for every archived cvar.
 * DOM-free.
 */

/** `PRODUCT_NAME`, which heads the file (`q_shared.h:43`): here, the port's own name. */
export const PRODUCT_NAME = 'playcanvas-quake3';

/** An archived cvar, as `Cvar_WriteVariables` writes it. */
export interface ArchivedCvar {
  name: string;
  value: string;
}

/**
 * The file, as `Com_WriteConfigToFile` writes it (`common.c:2927–2940`): the header, then
 * `Key_WriteBindings` (`cl_keys.c:1056–1068`), then `Cvar_WriteVariables` (`cvar.c:916–946`).
 *
 * @param binds - Each key's command. Unbound keys are left out, and the rest go in key order. With
 *   none, as a program with no client half has (`null_client.c:39–40`), there is no `unbindall`
 *   either.
 * @param cvars - The archived cvars, in the order to write them.
 */
export function writeConfig(
  binds: Iterable<readonly [number, string]> | undefined,
  cvars: Iterable<ArchivedCvar>
): string {
  const lines = [`// generated by ${PRODUCT_NAME}, do not modify`];
  if (binds) {
    lines.push('unbindall');
    const bound = [...binds].filter(([, command]) => command !== '').sort(([a], [b]) => a - b);
    for (const [key, command] of bound) lines.push(`bind ${keyToString(key)} "${command}"`);
  }
  for (const { name, value } of cvars) lines.push(`seta ${name} "${value}"`);
  return `${lines.join('\n')}\n`;
}
